USE DATABASE TEXTILE_PRODUCTION;
USE SCHEMA ML;

-- ML.FORECAST: TEXTILE_PRODUCTION_FORECAST
CREATE OR REPLACE SNOWFLAKE.ML.FORECAST ML.TEXTILE_PRODUCTION_FORECAST(
  INPUT_DATA => SYSTEM$REFERENCE('TABLE', 'CURATED.FORECAST_INPUT'),
  SERIES_COLNAME => 'ENTITY_ID',
  TIMESTAMP_COLNAME => 'DS',
  TARGET_COLNAME => 'Y'
  
);

CREATE OR REPLACE TABLE ML.TEXTILE_PRODUCTION_FORECAST_RESULTS AS
SELECT * FROM TABLE(ML.TEXTILE_PRODUCTION_FORECAST!FORECAST(FORECASTING_PERIODS => 14));

-- ML.ANOMALY_DETECTION: TEXTILE_PRODUCTION_ANOMALY
CREATE OR REPLACE SNOWFLAKE.ML.ANOMALY_DETECTION ML.TEXTILE_PRODUCTION_ANOMALY(
  INPUT_DATA => SYSTEM$REFERENCE('TABLE', 'CURATED.TREND_ANALYTICS'),
  SERIES_COLNAME => 'ENTITY_ID',
  TIMESTAMP_COLNAME => 'DS',
  TARGET_COLNAME => 'Y',
  LABEL_COLNAME => ''
);

CREATE OR REPLACE TABLE ML.TEXTILE_PRODUCTION_ANOMALY_RESULTS AS
SELECT * FROM TABLE(ML.TEXTILE_PRODUCTION_ANOMALY!DETECT_ANOMALIES(INPUT_DATA => SYSTEM$REFERENCE('TABLE', 'CURATED.TREND_ANALYTICS'), SERIES_COLNAME => 'ENTITY_ID', TIMESTAMP_COLNAME => 'DS', TARGET_COLNAME => 'Y'));

