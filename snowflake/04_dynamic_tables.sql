-- On-demand snapshots. No automatic freshness claim.
USE DATABASE IDENTIFIER($DEMO_DB);
USE SCHEMA CURATED;
USE WAREHOUSE IDENTIFIER($DEMO_WH);

CREATE DYNAMIC TABLE CURATED.PERFORMANCE_SUMMARY
  TARGET_LAG = DOWNSTREAM WAREHOUSE = __DEMO_WH__
  REFRESH_MODE = FULL INITIALIZE = ON_CREATE
AS
SELECT pl.ID AS ENTITY_ID, pl.NAME AS ENTITY_NAME,
       pl.REGION, pl.CATEGORY, pl.STATUS,
       COUNT(*) AS EVENT_COUNT, SUM(observation.CONSTRAINT_COUNT) AS CONSTRAINT_COUNT,
       SUM(observation.OPERATING_HOURS) AS OPERATING_HOURS,
       SUM(observation.PLANNED_HOURS) AS PLANNED_HOURS,
       SUM(observation.DOWNTIME_HOURS) AS DOWNTIME_HOURS,
       SUM(observation.PM_DUE) AS PM_DUE, SUM(observation.PM_COMPLETED) AS PM_COMPLETED,
       SUM(observation.WIP_ARRIVALS) AS WIP_ARRIVALS,
       SUM(observation.UNITS_COMPLETED) AS UNITS_COMPLETED, SUM(observation.COMMITTED_UNITS) AS COMMITTED_UNITS,
       SUM(observation.QUEUE_HOURS) AS QUEUE_HOURS,
       100.0 * SUM(observation.UNITS_COMPLETED) / NULLIF(SUM(observation.COMMITTED_UNITS), 0) AS PLAN_ATTAINMENT_PCT,
       SUM(observation.QUEUE_HOURS) / NULLIF(SUM(observation.WIP_ARRIVALS), 0) AS QUEUE_HOURS_PER_UNIT,
       100.0 * SUM(observation.OPERATING_HOURS) / NULLIF(SUM(observation.PLANNED_HOURS), 0) AS LINE_AVAILABILITY_PCT,
       100.0 * SUM(observation.PM_COMPLETED) / NULLIF(SUM(observation.PM_DUE), 0) AS PM_COMPLIANCE_PCT,
       MAX(observation.EVENT_DATE) AS SOURCE_WATERMARK
FROM RAW.LINE_DAILY observation
JOIN RAW.PRODUCTION_LINES pl ON pl.ID = observation.ENTITY_ID
GROUP BY pl.ID, pl.NAME, pl.REGION, pl.CATEGORY, pl.STATUS;

CREATE DYNAMIC TABLE CURATED.TREND_ANALYSIS
  TARGET_LAG = DOWNSTREAM WAREHOUSE = __DEMO_WH__
  REFRESH_MODE = FULL INITIALIZE = ON_CREATE
AS
SELECT EVENT_DATE AS METRIC_DATE, COUNT(*) AS EVENT_COUNT,
       SUM(UNITS_COMPLETED) AS UNITS_COMPLETED, SUM(COMMITTED_UNITS) AS COMMITTED_UNITS,
       SUM(WIP_ARRIVALS) AS WIP_ARRIVALS, SUM(QUEUE_HOURS) AS QUEUE_HOURS,
       SUM(CONSTRAINT_COUNT) AS CONSTRAINT_COUNT,
       100.0 * SUM(UNITS_COMPLETED) / NULLIF(SUM(COMMITTED_UNITS), 0) AS PLAN_ATTAINMENT_PCT
FROM RAW.LINE_DAILY
GROUP BY EVENT_DATE;

CREATE DYNAMIC TABLE CURATED.CONSTRAINT_CAUSES
  TARGET_LAG = DOWNSTREAM WAREHOUSE = __DEMO_WH__
  REFRESH_MODE = FULL INITIALIZE = ON_CREATE
AS
SELECT ROOT_CAUSE, SUM(CONSTRAINT_COUNT) AS CONSTRAINT_COUNT,
       SUM(DOWNTIME_HOURS) AS DOWNTIME_HOURS,
       SUM(COMMITTED_UNITS) - SUM(UNITS_COMPLETED) AS UNITS_SHORTFALL
FROM RAW.LINE_DAILY
WHERE CONSTRAINT_COUNT > 0
GROUP BY ROOT_CAUSE;

CREATE DYNAMIC TABLE CURATED.KPI_SUMMARY
  TARGET_LAG = DOWNSTREAM WAREHOUSE = __DEMO_WH__
  REFRESH_MODE = FULL INITIALIZE = ON_CREATE
AS
WITH observations AS (
  SELECT SUM(UNITS_COMPLETED) AS UNITS_COMPLETED, SUM(COMMITTED_UNITS) AS COMMITTED_UNITS,
         SUM(WIP_ARRIVALS) AS WIP_ARRIVALS, SUM(QUEUE_HOURS) AS QUEUE_HOURS,
         SUM(CONSTRAINT_COUNT) AS CONSTRAINT_EVENTS,
         SUM(OPERATING_HOURS) AS OPERATING_HOURS, SUM(PLANNED_HOURS) AS PLANNED_HOURS,
         MAX(EVENT_DATE) AS SOURCE_WATERMARK
  FROM RAW.LINE_DAILY
), lines AS (SELECT COUNT(*) AS LINE_COUNT FROM RAW.PRODUCTION_LINES),
qualification AS (
  SELECT 100.0 * SUM(LEAST(QUALIFIED_STATIONS, REQUIRED_STATIONS)) / NULLIF(SUM(REQUIRED_STATIONS), 0) AS COVERAGE_PCT
  FROM RAW.LINE_QUALIFICATION
), metrics AS (
  SELECT 1 AS SORT_ORDER, 'Plan Attainment' AS TITLE,
         100.0 * UNITS_COMPLETED / NULLIF(COMMITTED_UNITS, 0) AS VALUE_NUM, '%' AS UNIT FROM observations
  UNION ALL SELECT 2, 'Line Stoppages', CONSTRAINT_EVENTS, '' FROM observations
  UNION ALL SELECT 3, 'Queue Hours per Piece', QUEUE_HOURS / NULLIF(WIP_ARRIVALS, 0), ' h' FROM observations
  UNION ALL SELECT 4, 'WIP Released (pieces)', WIP_ARRIVALS, '' FROM observations
  UNION ALL SELECT 5, 'Line Availability', 100.0 * OPERATING_HOURS / NULLIF(PLANNED_HOURS, 0), '%' FROM observations
  UNION ALL SELECT 6, 'Lines Monitored', LINE_COUNT, '' FROM lines
  UNION ALL SELECT 7, 'Backup Machine Coverage', COVERAGE_PCT, '%' FROM qualification
)
SELECT metrics.SORT_ORDER, metrics.TITLE, metrics.VALUE_NUM,
       IFF(metrics.VALUE_NUM IS NULL, 'Unavailable',
           CASE WHEN metrics.TITLE = 'Queue Hours per Piece' THEN TRIM(TO_VARCHAR(metrics.VALUE_NUM, '990.00'))
                WHEN metrics.UNIT = '' THEN TRIM(TO_VARCHAR(ROUND(metrics.VALUE_NUM), '999,999,999,990'))
                ELSE TRIM(TO_VARCHAR(ROUND(metrics.VALUE_NUM, 1), '990.0')) END || metrics.UNIT) AS DISPLAY,
       'neutral' AS STATUS, observations.SOURCE_WATERMARK
FROM metrics CROSS JOIN observations;

ALTER DYNAMIC TABLE CURATED.PERFORMANCE_SUMMARY SUSPEND;
ALTER DYNAMIC TABLE CURATED.TREND_ANALYSIS SUSPEND;
ALTER DYNAMIC TABLE CURATED.CONSTRAINT_CAUSES SUSPEND;
ALTER DYNAMIC TABLE CURATED.KPI_SUMMARY SUSPEND;
