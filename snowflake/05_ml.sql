-- Line stoppage-risk scoring and plan-attainment forecast over the synthetic snapshot.
-- Predicts P(line stoppage in the next 7 days) per line and reports
-- out-of-time holdout metrics; nothing is seeded as a prediction.
USE DATABASE IDENTIFIER($DEMO_DB);
USE WAREHOUSE IDENTIFIER($DEMO_WH);

CREATE VIEW ML.CONSTRAINT_FEATURES AS
SELECT r.ENTITY_ID, r.EVENT_DATE, t.CATEGORY, t.AGE_YEARS,
       r.THROUGHPUT_GAP_PCT, r.QUEUE_UNITS,
       AVG(r.THROUGHPUT_GAP_PCT) OVER (PARTITION BY r.ENTITY_ID ORDER BY r.EVENT_DATE ROWS BETWEEN 6 PRECEDING AND CURRENT ROW) AS THROUGHPUT_GAP_7D,
       SUM(r.CONSTRAINT_COUNT) OVER (PARTITION BY r.ENTITY_ID ORDER BY r.EVENT_DATE ROWS BETWEEN 29 PRECEDING AND CURRENT ROW) AS CONSTRAINTS_30D,
       IFF(SUM(r.CONSTRAINT_COUNT) OVER (PARTITION BY r.ENTITY_ID ORDER BY r.EVENT_DATE ROWS BETWEEN 1 FOLLOWING AND 7 FOLLOWING) > 0,
           'CONSTRAINED', 'OK') AS LABEL,
       COUNT(*) OVER (PARTITION BY r.ENTITY_ID ORDER BY r.EVENT_DATE ROWS BETWEEN 1 FOLLOWING AND 7 FOLLOWING) AS FUTURE_DAYS
FROM RAW.LINE_DAILY r JOIN RAW.PRODUCTION_LINES t ON t.ID = r.ENTITY_ID
-- Grid power dips are not driven by the line, so they are excluded from training.
WHERE r.ROOT_CAUSE <> 'Grid power dip' OR r.CONSTRAINT_COUNT = 0;

-- Time-based split: train on older labelled days, hold out the most recent 14 labelled days.
CREATE VIEW ML.CONSTRAINT_TRAIN AS
SELECT CATEGORY, AGE_YEARS, THROUGHPUT_GAP_PCT, QUEUE_UNITS, THROUGHPUT_GAP_7D, CONSTRAINTS_30D, LABEL
FROM ML.CONSTRAINT_FEATURES
WHERE FUTURE_DAYS = 7 AND EVENT_DATE < DATEADD('day', -21, CURRENT_DATE());

CREATE VIEW ML.CONSTRAINT_HOLDOUT AS
SELECT ENTITY_ID, EVENT_DATE, CATEGORY, AGE_YEARS, THROUGHPUT_GAP_PCT, QUEUE_UNITS, THROUGHPUT_GAP_7D, CONSTRAINTS_30D, LABEL
FROM ML.CONSTRAINT_FEATURES
WHERE FUTURE_DAYS = 7 AND EVENT_DATE >= DATEADD('day', -21, CURRENT_DATE());

CREATE SNOWFLAKE.ML.CLASSIFICATION ML.CONSTRAINT_RISK_MODEL(
  INPUT_DATA => TABLE(ML.CONSTRAINT_TRAIN),
  TARGET_COLNAME => 'LABEL'
);

-- Out-of-time holdout: precision/recall at 0.5 versus the base rate.
CREATE TABLE ML.CONSTRAINT_RISK_HOLDOUT_METRICS AS
WITH scored AS (
  SELECT LABEL, ML.CONSTRAINT_RISK_MODEL!PREDICT(INPUT_DATA => OBJECT_CONSTRUCT(
           'CATEGORY', CATEGORY, 'AGE_YEARS', AGE_YEARS, 'THROUGHPUT_GAP_PCT', THROUGHPUT_GAP_PCT,
           'QUEUE_UNITS', QUEUE_UNITS, 'THROUGHPUT_GAP_7D', THROUGHPUT_GAP_7D, 'CONSTRAINTS_30D', CONSTRAINTS_30D)):probability:CONSTRAINED::FLOAT AS P
  FROM ML.CONSTRAINT_HOLDOUT
)
SELECT COUNT(*) AS N,
       AVG(IFF(LABEL = 'CONSTRAINED', 1, 0)) AS BASE_RATE,
       SUM(IFF(P >= 0.5 AND LABEL = 'CONSTRAINED', 1, 0)) / NULLIF(SUM(IFF(P >= 0.5, 1, 0)), 0) AS PRECISION_AT_50,
       SUM(IFF(P >= 0.5 AND LABEL = 'CONSTRAINED', 1, 0)) / NULLIF(SUM(IFF(LABEL = 'CONSTRAINED', 1, 0)), 0) AS RECALL_AT_50,
       CURRENT_TIMESTAMP() AS EVALUATED_AT
FROM scored;

-- Latest-day score per line (label unknown, so excluded from features).
CREATE TABLE ML.CONSTRAINT_RISK_SCORES AS
WITH latest AS (
  SELECT * FROM ML.CONSTRAINT_FEATURES
  QUALIFY ROW_NUMBER() OVER (PARTITION BY ENTITY_ID ORDER BY EVENT_DATE DESC) = 1
), scored AS (
  SELECT ENTITY_ID, EVENT_DATE,
         ML.CONSTRAINT_RISK_MODEL!PREDICT(INPUT_DATA => OBJECT_CONSTRUCT(
           'CATEGORY', CATEGORY, 'AGE_YEARS', AGE_YEARS, 'THROUGHPUT_GAP_PCT', THROUGHPUT_GAP_PCT,
           'QUEUE_UNITS', QUEUE_UNITS, 'THROUGHPUT_GAP_7D', THROUGHPUT_GAP_7D, 'CONSTRAINTS_30D', CONSTRAINTS_30D)) AS P
  FROM latest
)
SELECT ENTITY_ID, EVENT_DATE AS SCORED_AS_OF,
       ROUND(P:probability:CONSTRAINED::FLOAT, 4) AS CONSTRAINT_PROB_7D,
       CASE WHEN P:probability:CONSTRAINED::FLOAT >= 0.5 THEN 'High'
            WHEN P:probability:CONSTRAINED::FLOAT >= 0.25 THEN 'Medium' ELSE 'Low' END AS RISK_BAND,
       CURRENT_TIMESTAMP() AS SCORED_AT
FROM scored;

-- Network-wide plan-attainment forecast (14 days) from the daily series.
CREATE VIEW ML.DAILY_ATTAINMENT AS
SELECT EVENT_DATE::TIMESTAMP_NTZ AS TS, 100.0 * SUM(UNITS_COMPLETED) / SUM(COMMITTED_UNITS) AS PLAN_ATTAINMENT_PCT
FROM RAW.LINE_DAILY GROUP BY EVENT_DATE;

CREATE SNOWFLAKE.ML.FORECAST ML.ATTAINMENT_FORECAST_MODEL(
  INPUT_DATA => TABLE(ML.DAILY_ATTAINMENT),
  TIMESTAMP_COLNAME => 'TS',
  TARGET_COLNAME => 'PLAN_ATTAINMENT_PCT'
);

CREATE TABLE ML.ATTAINMENT_FORECAST AS
SELECT TS::DATE AS FORECAST_DATE, LEAST(100, FORECAST) AS PLAN_ATTAINMENT_PCT,
       LOWER_BOUND, LEAST(100, UPPER_BOUND) AS UPPER_BOUND
FROM TABLE(ML.ATTAINMENT_FORECAST_MODEL!FORECAST(FORECASTING_PERIODS => 14));
